const SEM = (s) => String(s || "").normalize("NFC").toLowerCase();
const MAPA = new Map();
PALAVRAS.forEach((p) => p.formas.forEach((f) => MAPA.set(SEM(f), p)));

export const achaPalavra = (id) => PALAVRAS.find((p) => p.id === id) || null;
export const palavraDoToken = (tok) => MAPA.get(SEM(tok)) || null;

// Quebra um texto em pedaços: { t: "texto" } ou { t: "côvados", p: <palavra> }
export function segmentarPalavras(texto) {
  const out = []; const re = /[\p{L}]+/gu; let ult = 0, m;
  while ((m = re.exec(texto))) {
    const p = palavraDoToken(m[0]);
    if (!p) continue;
    if (m.index > ult) out.push({ t: texto.slice(ult, m.index) });
    out.push({ t: m[0], p }); ult = m.index + m[0].length;
  }
  if (ult < texto.length) out.push({ t: texto.slice(ult) });
  return out.length ? out : [{ t: texto }];
}
